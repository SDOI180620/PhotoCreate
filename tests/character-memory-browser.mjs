  await loginBrowser(page,base);
  await expect(page.getByRole('button',{name:'套用至顧客攝影棚',exact:true})).toBeEnabled();
  await expect.poll(()=>store.read().draft.expressionIds).toEqual(['expression-smile']);
  await expect.poll(()=>store.read().workbenchDrafts.combinations.expressionIds).toEqual(['expression-smile']);
  await expect.poll(()=>store.read().draft.expressionId).toBe('');
  await page.getByRole('button',{name:'選擇角色參考圖',exact:true}).click();
