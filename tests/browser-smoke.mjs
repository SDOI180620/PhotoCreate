const verifyGalleryPhotoLayout = async () => {
  const ratios = new Set();
  for(const photo of await page.locator('.gallery-photo').all()) {
    const image = photo.locator('img');
    await image.scrollIntoViewIfNeeded();
    await expect.poll(() => image.evaluate(node => node.complete && node.naturalWidth > 0)).toBe(true);
    const layout = await photo.evaluate(node => {
      const image = node.querySelector('img');
      const photoRect = node.getBoundingClientRect();
      const imageRect = image.getBoundingClientRect();
      const checkRect = node.querySelector('.gallery-check').getBoundingClientRect();
      return {
        ratio:image.naturalWidth / image.naturalHeight,
        actualRatio:imageRect.width / imageRect.height,
        heightGap:Math.abs(photoRect.height - imageRect.height),
        widthGap:Math.abs(photoRect.width - imageRect.width),
        checkInside:checkRect.left >= imageRect.left && checkRect.top >= imageRect.top && checkRect.right <= imageRect.right && checkRect.bottom <= imageRect.bottom,
        checkInset:Math.abs(checkRect.top - imageRect.top - 10) < 1 && Math.abs(checkRect.left - imageRect.left - 10) < 1,
      };
    });
    if(Math.abs(layout.actualRatio - layout.ratio) > 0.01 || layout.heightGap > 1 || layout.widthGap > 1) throw new Error('Gallery photo must follow its actual image ratio without letterboxing or cropping.');
    if(!layout.checkInside || !layout.checkInset) throw new Error('Gallery selection control must overlay the actual photo in the top-left corner.');
    ratios.add(layout.ratio.toFixed(2));
  }
  if(ratios.size !== 3) throw new Error('Gallery layout coverage must include landscape, portrait and square images.');
};

