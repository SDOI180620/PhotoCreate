import {chromium,expect} from '@playwright/test';
import fs from 'node:fs';
import {createApp} from '../server/index.js';
import {environmentFixture} from './environment-fixtures.js';

const fixture=environmentFixture(),errors=[];
const {app,store,environment}=createApp({...fixture,environmentOptions:fixture,directoryPicker:async()=>fixture.root});
store.mutate(state=>{state.settings.connectionMode='url';state.settings.comfyDirectory=fixture.root;});
const server=app.listen(0,'127.0.0.1');await new Promise(resolve=>server.once('listening',resolve));
const browser=await chromium.launch({executablePath:process.env.PHOTOCREATE_BROWSER || 'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1080}});page.on('pageerror',error=>errors.push(error.message));
fs.mkdirSync('test-results',{recursive:true});
try {
  await page.goto(`http://127.0.0.1:${server.address().port}`);
  await page.getByRole('button',{name:'工作流與連線設定',exact:true}).click();
  const dialog=page.getByRole('dialog');await expect(dialog).toBeVisible();
  const bind=dialog.getByRole('button',{name:'綁定此 ComfyUI',exact:true});await expect(bind).toBeDisabled();
  await dialog.getByRole('textbox',{name:'ComfyUI 網址',exact:true}).fill('http://other-comfy.test:8188');
  fixture.controls.missingModel=true;await dialog.getByRole('button',{name:'測試工作流',exact:true}).click();
  await expect(dialog.getByText('尚未通過工作流測試。',{exact:true})).toBeVisible();await expect(bind).toBeDisabled();
  await expect(dialog.getByText(/UNETLoader 缺少或不支援 unet_name/).first()).toBeVisible();
  fixture.controls.missingModel=false;await dialog.getByRole('button',{name:'測試工作流',exact:true}).click();
  await expect(dialog.getByText('三個階段均可用，可以綁定。',{exact:true})).toBeVisible();await expect(bind).toBeEnabled();
  await dialog.getByRole('textbox',{name:'ComfyUI 網址',exact:true}).fill('http://changed-comfy.test:8188');await expect(bind).toBeDisabled();
  await dialog.getByRole('button',{name:'測試工作流',exact:true}).click();await expect(bind).toBeEnabled();
  await page.screenshot({path:'test-results/environment-url-desktop.png',fullPage:true});
  await bind.click();await expect.poll(()=>store.read().settings.comfyUrl).toBe('http://changed-comfy.test:8188');await expect.poll(()=>store.read().settings.connectionMode).toBe('url');
  await dialog.getByRole('button',{name:/本機目錄/}).click();
  await expect(dialog.getByRole('button',{name:'安裝環境',exact:true})).toBeVisible();
  await dialog.getByRole('textbox',{name:'ComfyUI 目錄',exact:true}).fill('');
  await expect(dialog.getByRole('button',{name:'保存安裝設定',exact:true})).toBeDisabled();
  await dialog.getByRole('button',{name:'選擇目錄',exact:true}).click();
  await expect(dialog.getByRole('textbox',{name:'ComfyUI 目錄',exact:true})).toHaveValue(fixture.root);
  await expect(dialog.getByText('模型清單與下載來源')).toBeVisible();
  await expect(dialog.getByRole('button',{name:'檢查並載入',exact:true})).toBeDisabled();
  await dialog.getByRole('textbox',{name:'ComfyUI 網址',exact:true}).fill('http://127.0.0.1:8188');
  await page.screenshot({path:'test-results/environment-directory-desktop.png',fullPage:true});
  await dialog.getByRole('button',{name:'安裝環境',exact:true}).click();
  await expect.poll(()=>environment.status()?.status).toBe('completed');
  if(store.read().settings.comfyUrl!=='http://changed-comfy.test:8188') throw new Error('Installation switched the active connection before verification');
  await expect(dialog.getByRole('button',{name:'檢查並載入',exact:true})).toBeEnabled();
  await expect(dialog.getByText('安裝完成，請重新啟動 ComfyUI 後按「檢查並載入」。',{exact:true})).toBeVisible();
  await dialog.getByRole('button',{name:'檢查並載入',exact:true}).click();await expect.poll(()=>store.read().settings.connectionMode).toBe('directory');
  await expect(dialog.getByText('環境已就緒，工作流已載入。',{exact:true})).toBeVisible();
  await dialog.getByRole('button',{name:'完成',exact:true}).click();
  await page.reload();await page.getByRole('button',{name:'工作流與連線設定',exact:true}).click();
  await expect(dialog.getByRole('button',{name:/本機目錄/})).toHaveAttribute('aria-pressed','true');
  await expect(dialog.getByRole('textbox',{name:'ComfyUI 目錄',exact:true})).toHaveValue(fixture.root);
  await page.screenshot({path:'test-results/environment-ready-desktop.png',fullPage:true});
  if(errors.length) throw new Error('Browser errors: '+errors.join(' · '));
  if(fixture.controls.requests.some(request=>request.method!=='GET')) throw new Error('Environment UI unexpectedly submitted ComfyUI mutation');
  console.log('Environment PC UI passed: failed checks, binding invalidation, directory picker, installation, activation and saved environment.');
} finally {await browser.close();server.close();environment.close();store.close();}
